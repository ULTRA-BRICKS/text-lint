"""Capture Bun Unicode primitives; assemble ranges and case-fold groups in Python."""
from __future__ import annotations

import importlib.util
from pathlib import Path

_spec = importlib.util.spec_from_file_location('capture_foundation', Path(__file__).with_name('capture_foundation.py'))
foundation = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(foundation)

# These are engine primitives, not copied tg-cli implementation. Python supplies
# codepoints and computes all ranges and graph components from the returned facts.
PROBE = r'''
const points = await Bun.stdin.json();
console.log(JSON.stringify(points.map(cp => {
  const ch = String.fromCodePoint(cp);
  return [cp, [/[\p{L}\p{M}\p{Cf}]/u.test(ch), /\p{L}/u.test(ch) && !/\p{Lm}/u.test(ch), /[\p{L}\p{N}]/u.test(ch)],
    [ch.toUpperCase(), ch.toLowerCase()].filter(q => Array.from(q).length === 1 && q !== ch && new RegExp('^\\u{' + cp.toString(16) + '}$', 'iu').test(q)).map(q => q.codePointAt(0))];
})));
'''
EQUIVALENT = r'''
const groups = await Bun.stdin.json();
console.log(JSON.stringify(groups.every(g => g.every(a => g.every(b => new RegExp('^\\u{' + a.toString(16) + '}$', 'iu').test(String.fromCodePoint(b)))))));
'''


def ranges(points):
    result = []
    for cp in sorted(set(points)):
        if not isinstance(cp, int) or not 0 <= cp <= 0x10FFFF:
            raise ValueError('invalid Unicode codepoint')
        if result and result[-1][1] == cp - 1:
            result[-1] = (result[-1][0], cp)
        else:
            result.append((cp, cp))
    return result


def fold_groups(edges):
    graph = {}
    for a, b in edges:
        graph.setdefault(a, set()).add(b)
        graph.setdefault(b, set()).add(a)
    seen, groups = set(), []
    for cp in sorted(graph):
        if cp in seen:
            continue
        group, pending = set(), [cp]
        while pending:
            value = pending.pop()
            if value not in group:
                group.add(value)
                pending.extend(graph[value] - group)
        seen.update(group)
        groups.append(tuple(sorted(group)))
    return groups


def probe(checkout, bun, points):
    foundation.prepare(checkout, bun)
    ranges(points)  # Validate scalar bounds, including surrogate codepoints.
    return foundation.run_bun(bun, PROBE, points)


def capture(checkout, bun):
    foundation.prepare(checkout, bun)
    tables = {name: [] for name in ('LETTERISH', 'BASE_LETTER', 'LETTER_NUMBER')}
    edges = []
    for start in range(0, 0x110000, 8192):
        rows = foundation.run_bun(bun, PROBE, list(range(start, min(start + 8192, 0x110000))))
        for cp, flags, candidates in rows:
            for name, hit in zip(tables, flags):
                if hit:
                    tables[name].append(cp)
            edges.extend((cp, candidate) for candidate in candidates)
    groups = fold_groups(edges)
    if foundation.run_bun(bun, EQUIVALENT, groups) is not True:
        raise ValueError('non-equivalent case-fold group')
    return {name: ranges(points) for name, points in tables.items()}, groups


def render(tables, groups):
    # Preserve the original artifact's header for byte reproduction; its historical
    # TS command is superseded by tests/oracles/README.md.
    header = ('"""Unicode 17.0 categories and simple folds captured from Bun 1.4.2.\n\n'
              'Generated by tests/oracles/capture_unicode.ts with revision\n'
              '744846f844374847c902b5e7fd59b4342a51ef99 (ICU 78.3). Regenerate with:\n'
              '  bun tests/oracles/capture_unicode.ts > text_lint/unicode_categories.py\n'
              'The source guards use L/M/Cf and L excluding Lm; dictionary boundaries use L/N.\n'
              '"""\n\nfrom .unicode_scripts import _ranges\n\n')
    def lines(values):
        return ''.join('    ' + ', '.join('(' + ', '.join(f'0x{cp:04X}' for cp in group) + ')'
                                        for group in values[i:i + 4]) + ',\n' for i in range(0, len(values), 4))
    return header + ''.join(f'{name} = _ranges(\n' + lines(values) + ')\n\n' for name, values in tables.items()) + 'SIMPLE_FOLDS = (\n' + lines(groups) + ')\n'


if __name__ == '__main__':
    args = foundation.parser().parse_args()
    foundation.write_capture(args, render(*capture(args.checkout, args.bun)))
