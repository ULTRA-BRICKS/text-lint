r"""The Unicode scripts text-lint's script rules test, as codepoint ranges.

Python's `re` has no `\p{sc=…}`. These tables are what tg-cli's guards match with
`\p{sc=Latin}`, `\p{sc=Cyrillic}`, `\p{sc=Han}`, `\p{sc=Hiragana}`, `\p{sc=Katakana}` and
`\p{sc=Hangul}`: generated by testing every codepoint against those regexes in Bun 1.4.2
(ICU 78.3, Unicode 17.0), so text-lint and tg-cli agree on which characters each script holds.
"""

import bisect


def _ranges(*pairs):
    return tuple(start for start, _ in pairs), tuple(end for _, end in pairs)


def in_script(ch, script):
    """Whether the character ``ch`` belongs to ``script`` (one of the tables below)."""
    starts, ends = script
    cp = ord(ch)
    i = bisect.bisect_right(starts, cp) - 1
    return i >= 0 and cp <= ends[i]


