def no_params(params):
    if params:
        raise ValueError("this rule takes no params")


def matches(rule, unit, pattern):
    return [finding(rule, unit, m.start(), m.end(), space="raw", match=m.group())
            for m in pattern.finditer(unit.raw)]


def emoji(rule, unit, ctx):
    return matches(rule, unit, EMOJI)


def formatting(rule, unit, ctx):
    return matches(rule, unit, FORMATTING)


def first_person(rule, unit, ctx):
    # The classifier sees all gating fields; attach its single result to the first one.
    target = next((u for u in ctx.units if u.gate and u.text.strip()), None)
    probability = ctx.laya.get("first_person")
    if unit is not target or probability is None or probability >= .5:
        return []
    return [finding(rule, unit, 0, 0, space="raw", match="")]
